REQUIRED_SECTIONS = (
    'Professional summary', 'Professional experience', 'Technical skills',
    'Education', 'Certifications', 'Languages',
)
_INTERNAL_PATTERNS = (
    r'draft prepared from', r'source profile', r'as listed in (?:the )?candidate profile',
    r'not included in (?:the )?profile', r'candidate profile', r'internal (?:ai|note|comment)',
    r'(?:generated by|written by) (?:an? )?ai', r'ai-generated',
)
_SKILL_GROUPS = {
    'Quality assurance': [
        'Manual QA', 'Exploratory testing', 'Functional testing', 'Regression testing',
        'Smoke testing', 'Integration testing', 'Responsive testing', 'Cross-browser testing',
        'Accessibility testing', 'UAT', 'Web testing', 'Mobile testing', 'Agile', 'Scrum',
        'Test plans', 'Test cases', 'QA documentation', 'Defect investigation',
    ],
    'Automation': [
        'Playwright', 'JavaScript', 'Node.js', 'Selenium WebDriver', 'C#', 'BDD',
        'Page Object Model',
    ],
    'API and data': [
        'SQL', 'API testing', 'REST', 'JSON', 'JSON:API', 'Backend validation', 'Data integrity',
    ],
    'CMS platforms': [
        'CMS validation', 'Drupal', 'Contentful', 'Contentstack', 'CMS migrations',
        'Content models', 'Publishing workflows', 'Field mapping',
    ],
    'Performance and visual testing': [
        'Visual regression', 'BackstopJS', 'Performance testing', 'Load testing', 'k6',
    ],
    'Tools': [
        'Figma', 'Storybook', 'Chromatic', 'Chrome DevTools', 'Azure DevOps',
        'Microsoft Dynamics CRM', 'AI-assisted testing', 'OpenAI Codex',
    ],
}


class CvValidationError(ValueError):
    """Raised when a CV is incomplete, contains internal notes, or exceeds profile facts."""


def _normal(value: str) -> str:
    return re.sub(r'\s+', ' ', value).strip().casefold()


def _safe_inline(value: str) -> str:
    value = re.sub(r'[\r\n]+', ' ', value).strip()
    return re.sub(r'[<>\[\]`]', '', value)


def _tokens(text: str) -> set[str]:
    return set(re.findall(r'[a-z0-9+#.]+', text.casefold()))


def _rank(items: list[str], description: str) -> list[str]:
    words = _tokens(description)
    normalized_description = _normal(description)
    indexed = list(enumerate(items))
    return [item for _, item in sorted(indexed, key=lambda pair: (
        -(1 if _normal(pair[1]) in normalized_description else 0),
        -len(_tokens(pair[1]) & words), pair[0]))]


_GROUP_TERMS = {
    'Quality assurance': ('qa', 'quality assurance', 'manual testing', 'regression testing'),
    'Automation': ('automation', 'playwright', 'selenium', 'bdd'),
    'API and data': ('api', 'rest', 'sql', 'backend'),
    'CMS platforms': ('cms', 'drupal', 'contentful', 'contentstack'),
    'Performance and visual testing': ('performance testing', 'load testing', 'visual regression', 'k6'),
    'Tools': ('figma', 'storybook', 'chromatic', 'devtools'),
}


def _grouped_skills(candidate: Candidate, description: str = '', target_title: str = '') -> dict[str, list[str]]:
    groups = {name: [skill for skill in skills if skill in candidate.skills]
              for name, skills in _SKILL_GROUPS.items()}
    groups = {name: skills for name, skills in groups.items() if skills}
    grouped = [skill for skills in groups.values() for skill in skills]
    if Counter(grouped) != Counter(candidate.skills):
        raise CvValidationError('Every profile skill must appear exactly once in the CV skill groups')
    if not description:
        return groups
    normalized = _normal(description)
    normalized_title = _normal(target_title)

    def matches(phrase: str, text: str) -> bool:
        return bool(re.search(r'(?<![a-z0-9])' + re.escape(phrase) + r'(?![a-z0-9])', text))

    def relevance(group: str) -> int:
        aliases = _GROUP_TERMS[group]
        score = sum(matches(term, normalized) for term in aliases)
        # Specific title wording should outweigh incidental repetition in a long posting.
        if group == 'Automation' and matches('automation', normalized_title):
            score += 100
        if group == 'Quality assurance' and (matches('qa', normalized_title)
                                               or matches('quality assurance', normalized_title)):
            score += 20
        return score

    ordered = sorted(groups, key=lambda group: -relevance(group))
    return {name: _rank(groups[name], description) for name in ordered}


def render_cv(candidate: Candidate, *, target_title: str = '', target_employer: str = '',
              description: str = '') -> str:
    if not candidate.professional_summary.strip():
        raise CvValidationError('The verified candidate profile is missing a professional summary')
    if not candidate.experience:
        raise CvValidationError('The verified candidate profile is missing structured work history')
    lines = [f'# {candidate.name}', '', candidate.location]
    if candidate.github and candidate.github != 'unknown':
        lines[-1] += f' | GitHub: {candidate.github}'
    if candidate.email and candidate.email != 'unknown':
        lines.append(f'Email: {candidate.email}')
    if candidate.telephone and candidate.telephone != 'unknown':
        lines.append(f'Telephone: {candidate.telephone}')
    if candidate.work_authorization and candidate.work_authorization != 'unknown':
        lines.append(f'Work authorization: {candidate.work_authorization}')
    if target_title:
        lines += ['', f'**Target position:** {_safe_inline(target_title)}']
        if target_employer:
            lines[-1] += f' | **Target employer:** {_safe_inline(target_employer)}'
    lines += ['', '## Professional summary', '', candidate.professional_summary.strip(), '',
              '## Professional experience', '']
    for role in candidate.experience:
        lines.append(f'### {role.title} | {role.company} | {role.dates}')
        if role.location:
            lines.append(f'**Location:** {role.location}')
        bullets = _rank(role.bullets, description) if description else role.bullets
        lines.extend(f'- {bullet}' for bullet in bullets)
        lines.append('')
    lines += ['## Technical skills', '']
    for group, skills in _grouped_skills(candidate, description, target_title).items():
        lines.append(f'- **{group}:** ' + '; '.join(skills))
    lines += ['', '## Education', '']
    lines.extend(f'- {item}' for item in candidate.education)
    lines += ['', '## Certifications', '']
    lines.extend(f'- {item}' for item in candidate.certifications)
    lines += ['', '## Languages', '']
    lines.extend(f'- {item}' for item in candidate.languages)
    return '\n'.join(lines).rstrip() + '\n'


def _section(text: str, heading: str) -> str:
    match = re.search(r'^## ' + re.escape(heading) + r'\s*$', text, re.M)
    if not match:
        raise CvValidationError(f'Missing required section: {heading}')
    end = re.search(r'^## .+$', text[match.end():], re.M)
    return text[match.end():match.end() + end.start() if end else len(text)].strip()


def _bullets(section: str) -> list[str]:
    return [line[2:].strip() for line in section.splitlines() if line.startswith('- ')]


def validate_cv_document(text: str, candidate: Candidate) -> None:
    lowered = text.casefold()
    if any(re.search(pattern, lowered, re.I) for pattern in _INTERNAL_PATTERNS):
        raise CvValidationError('CV contains internal profile or AI commentary')
    for heading in REQUIRED_SECTIONS:
        _section(text, heading)
    headings = re.findall(r'^## (.+)$', text, re.M)
    if headings != list(REQUIRED_SECTIONS):
        raise CvValidationError('CV must contain each required section exactly once and in order')
    if candidate.name not in text or candidate.location not in text:
        raise CvValidationError('CV is missing verified candidate name or location')
    if candidate.github and candidate.github != 'unknown' and candidate.github not in text:
        raise CvValidationError('CV is missing the verified GitHub contact')
    if candidate.email != 'unknown' and candidate.email not in text:
        raise CvValidationError('CV is missing the verified email contact')
    if candidate.telephone != 'unknown' and candidate.telephone not in text:
        raise CvValidationError('CV is missing the verified telephone contact')
    if candidate.work_authorization != 'unknown' and candidate.work_authorization not in text:
        raise CvValidationError('CV is missing verified work-authorization information')
    if _section(text, 'Professional summary') != candidate.professional_summary.strip():
        raise CvValidationError('Professional summary differs from the verified profile summary')

    # Restrict all text outside the verified sections to known contact and optional
    # target-role lines. This prevents unsupported claims being hidden in the header.
    first_heading = re.search(r'^## ', text, re.M)
    header = text[:first_heading.start()] if first_heading else text
    allowed_header = {f'# {candidate.name}', candidate.location}
    if candidate.github and candidate.github != 'unknown':
        allowed_header.add(f'{candidate.location} | GitHub: {candidate.github}')
    if candidate.email != 'unknown':
        allowed_header.add(f'Email: {candidate.email}')
    if candidate.telephone != 'unknown':
        allowed_header.add(f'Telephone: {candidate.telephone}')
    if candidate.work_authorization != 'unknown':
        allowed_header.add(f'Work authorization: {candidate.work_authorization}')
    for line in header.splitlines():
        line = line.strip()
        if not line:
            continue
        if line in allowed_header or re.fullmatch(r'\*\*Target position:\*\* .+(?: \| \*\*Target employer:\*\* .+)?', line):
            continue
        raise CvValidationError('CV header contains unsupported candidate information')

    experience = _section(text, 'Professional experience')
    expected_headers = {f'### {entry.title} | {entry.company} | {entry.dates}' for entry in candidate.experience}
    expected_bullets = [bullet for entry in candidate.experience for bullet in entry.bullets]
    actual_headers = {line for line in experience.splitlines() if line.startswith('### ')}
    actual_bullets = _bullets(experience)
    allowed_locations = {f'**Location:** {entry.location}' for entry in candidate.experience if entry.location}
    actual_locations = {line for line in experience.splitlines() if line.startswith('**Location:** ')}
    if actual_headers != expected_headers or Counter(actual_bullets) != Counter(expected_bullets):
        raise CvValidationError('Professional experience contains missing or unsupported profile facts')
    if actual_locations != allowed_locations:
        raise CvValidationError('Professional experience contains unsupported locations')
    allowed_lines = expected_headers | allowed_locations | {f'- {item}' for item in expected_bullets}
    if any(line.strip() and line.strip() not in allowed_lines for line in experience.splitlines()):
        raise CvValidationError('Professional experience contains unverified wording')

    skill_section = _section(text, 'Technical skills')
    skill_lines = [line for line in skill_section.splitlines() if line.strip()]
    if any(not line.startswith('- **') for line in skill_lines):
        raise CvValidationError('Technical skills contain unsupported wording')
    parsed_skills = []
    for line in skill_lines:
        if ':** ' not in line:
            raise CvValidationError('Technical skill group is malformed')
        parsed_skills.extend(item.strip() for item in line.split(':** ', 1)[1].split(';') if item.strip())
    if Counter(parsed_skills) != Counter(candidate.skills):
        raise CvValidationError('Technical skills differ from verified candidate skills')
    for heading, facts in (('Education', candidate.education),
                            ('Certifications', candidate.certifications),
                            ('Languages', candidate.languages)):
        section_lines = [line.strip() for line in _section(text, heading).splitlines() if line.strip()]
        if any(not line.startswith('- ') for line in section_lines):
            raise CvValidationError(f'{heading} contains unsupported wording')
        if Counter(_bullets(_section(text, heading))) != Counter(facts):
            raise CvValidationError(f'{heading} contains missing or unsupported facts')


def validate_private_git_policy(repo_root: Path, private_paths: list[Path]) -> None:
    root = repo_root.resolve()
    tracked = subprocess.run(['git', 'ls-files', '-z'], cwd=root, check=True,
                             capture_output=True).stdout.decode('utf-8').split('\0')
    sensitive = []
    for entry in filter(None, tracked):
        path = Path(entry)
        lowered = entry.casefold()
        if ('private' in {part.casefold() for part in path.parts}
                or path.name.casefold().startswith('candidate_profile')
                or path.suffix.casefold() in {'.pdf', '.db', '.sqlite', '.sqlite3', '.pem', '.key'}
                or 'credential' in path.name.casefold()
                or path.name.casefold() in {'.env', 'secrets.json'}):
            sensitive.append(entry)
    if sensitive:
        raise CvValidationError('Git tracks a private candidate artifact')
    for path in private_paths:
        absolute = path if path.is_absolute() else root / path
        try:
            relative = absolute.resolve().relative_to(root).as_posix()
        except ValueError as exc:
            raise CvValidationError('Private CV output must stay inside the project') from exc
        result = subprocess.run(['git', 'check-ignore', '-q', '--', relative], cwd=root)
        if result.returncode != 0:
            raise CvValidationError(f'Private output is not ignored by Git: {relative}')


def tailor_cv(master_text: str, candidate: Candidate, *, target_title: str,
              target_employer: str, description: str) -> str:
    validate_cv_document(master_text, candidate)
    tailored = render_cv(candidate, target_title=target_title,
                         target_employer=target_employer,
                         description=description)
    validate_cv_document(tailored, candidate)
    return tailored


def _database_path(root: Path) -> Path:
    url = make_url(os.getenv('DATABASE_URL', 'sqlite:///' + str(root / 'data' / 'jobs.db')))
    if url.get_backend_name() != 'sqlite' or not url.database:
        raise CvValidationError('CV generation requires the local SQLite database')
    path = Path(url.database)
    return path if path.is_absolute() else root / path


def generate_master_cv(root: Path = ROOT) -> Path:
    root = root.resolve()
    candidate = profile()
    output = root / 'private' / 'cv' / 'master_cv.md'
    text = render_cv(candidate)
    validate_cv_document(text, candidate)
    validate_private_git_policy(root, [root / 'candidate_profile.json', output])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8')
    return output


def generate_shortlisted_cv(job_id: int, root: Path = ROOT) -> Path:
    root = root.resolve()
    candidate = profile()
    master_path = root / 'private' / 'cv' / 'master_cv.md'
    profile_path = root / 'candidate_profile.json'
    master_text = master_path.read_text(encoding='utf-8-sig')
    validate_cv_document(master_text, candidate)
    database_path = _database_path(root)
    uri = 'file:' + quote(database_path.as_posix(), safe=':/') + '?mode=ro'
    with sqlite3.connect(uri, uri=True) as connection:
        record = connection.execute('SELECT status, payload FROM jobs WHERE id=?', (job_id,)).fetchone()
    if record is None:
        raise CvValidationError(f'Vacancy ID {job_id} was not found')
    status, payload = record
    if status != 'Shortlisted':
        raise CvValidationError('CV generation is limited to vacancies currently marked Shortlisted')
    job = Job.model_validate_json(payload)
    tailored = tailor_cv(master_text, candidate, target_title=job.title,
                         target_employer=job.company, description=job.description)
    slug = re.sub(r'[^a-z0-9]+', '-', f'{job.company}-{job.title}'.casefold()).strip('-')
    output = root / 'private' / 'application_pilot' / f'job-{job_id}-{slug}' / 'cv_draft.md'
    validate_private_git_policy(root, [profile_path, master_path, output])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(tailored, encoding='utf-8')
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description='Build the private Master CV or tailor one for a Shortlisted vacancy.')
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--build-master', action='store_true', help='Build/refresh private/cv/master_cv.md from verified profile facts')
    mode.add_argument('--job-id', type=int, help='Stable SQLite ID of a Shortlisted vacancy')
    args = parser.parse_args()
    try:
        output = generate_master_cv() if args.build_master else generate_shortlisted_cv(args.job_id)
        print(output.resolve())
    except (CvValidationError, OSError, ValueError) as exc:
        parser.error(str(exc))


if __name__ == '__main__':
    main()
